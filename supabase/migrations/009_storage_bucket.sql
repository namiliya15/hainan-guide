-- Миграция: создание bucket'а в Storage для фото мест.
--
-- Раньше были только политики доступа (007_storage_policy.sql), но не сам
-- bucket — это два разных шага в Supabase. Без бакета загрузка файла
-- получает ошибку до того, как вообще доходит до проверки политик,
-- а добавление фото по ссылке работало нормально (не использует Storage).
--
-- Уже применено напрямую в твоей базе через прямой доступ, но добавляю
-- сюда, чтобы миграции полностью описывали структуру проекта — например,
-- если будешь разворачивать проект на новом Supabase-проекте с нуля.
--
-- Как применить (если ещё не запускала): Supabase Dashboard → SQL Editor.

insert into storage.buckets (id, name, public)
values ('place-images', 'place-images', true)
on conflict (id) do update set public = true;
